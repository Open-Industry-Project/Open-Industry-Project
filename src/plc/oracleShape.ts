// What MATIEC's generated C looks like, and the replay harness written against it.
//
// This is the knowledge tier 2 of the external oracle needs (scripts/oracle-matiec.mjs
// --execute): how to find the program instance iec2c emitted, which files are their own
// translation unit, how a variable is spelled in the generated struct, and what a standalone
// driver has to supply. It lives here, as typed and unit-tested code, because it can only be
// exercised for real where MATIEC runs, which is CI, and each wrong assumption costs a CI round
// trip to find. src/plc/oracleShape.test.ts checks every one against excerpts of real generated
// files, so a bad assumption fails in `npm test` instead.
//
// Everything here is pure: text in, facts or C source out. The script keeps the file system,
// the compiler and the diffing. That split is also what makes these testable.
//
// No value imports: the oracle script imports this module through Node's bare TypeScript
// loader, which strips types but resolves no extensionless specifiers.

/** The corpus case shape this module needs; the corpus's own `Case` is a superset. */
export interface HarnessCase {
  name: string
  steps: { in?: Record<string, unknown>; dt?: number }[]
}

/** One variable the harness must print each scan, and how the golden reads it. */
export interface WatchedVar {
  name: string
  kind: string
}

export interface HarnessFacts {
  /** the generated instance symbol, e.g. `RES0__INST0` */
  instance: string
  /** its struct type, e.g. `MAIN_data__` */
  structType: string
  watched: WatchedVar[]
  /** declared IEC type per variable, upper-cased, from {@link declaredTypes} */
  types?: Map<string, string>
  /** a CONFIGURATION's program instances, when a case declares its own: a watched or written
   *  `Instance.Name` is reached on the instance it names */
  instances?: InstanceFacts[]
  /** the program's LOCATED variables, upper-cased, from {@link locatedNames}: reached through a pointer */
  located?: Set<string>
}

/** One program instance of a CONFIGURATION, as {@link parseInstances} found it plus its types. */
export interface InstanceFacts {
  /** the instance name as MATIEC spells it, e.g. `FASTCOUNT` */
  name: string
  /** its generated symbol, e.g. `RES0__FASTCOUNT` */
  symbol: string
  structType: string
  types: Map<string, string>
  located?: Set<string>
}

/**
 * Prototypes for the shims the harness defines, force-included into every translation unit.
 *
 * MATIEC's generated POU code calls `_____time_add`/`_____time_sub`/`_____time_mul` for the
 * ST operators on TIME, and no matiec header declares them (see the harness for the full
 * note). A call with no declaration in scope is not a warning to shrug at here: C assumes
 * `int`, while these return a TIME STRUCT, so gcc would link the program and then compute
 * nonsense. Including this ahead of everything makes the declarations reach the generated
 * units; `iec_std_lib.h` is include-guarded, so pulling it in early is free.
 */
export const SHIM_DECLARATIONS = `/* generated by scripts/oracle-matiec.mjs - see renderHarness() */
/* libc must be included first. matiec's iec_std_functions.h defines
   function-like macros named __acos, __sqrt, __cos, __sin, __tan, __exp and __log - which
   are precisely the reserved internal names glibc's <math.h> also declares. Reach math.h
   second and its own \`extern double __acos (double);\` expands one of those macros into a
   \`static inline\` definition, so gcc reports "multiple storage classes in declaration
   specifiers" for every math function in the header, and every case fails to build. Because
   this header is force-included ahead of each translation unit, putting libc at the top of
   IT is what fixes the order everywhere. (MSVC's UCRT declares no such aliases, so a Windows
   clang replay does not reproduce this - CI caught it.) */
#include <stdio.h>
#include <stdarg.h>
#include <math.h>
#include "iec_std_lib.h"
TIME _____time_add(TIME a, TIME b);
TIME _____time_sub(TIME a, TIME b);
TIME _____time_mul(TIME a, LREAL b);
`

/**
 * Find the generated program instance in the resource file's text.
 *
 * MATIEC emits:
 *
 *     MAIN_data__ RES0__INST0;
 *     #define INST0 RES0__INST0
 *
 * so the type is the program name with a `_data__` suffix, and the symbol is joined from the
 * RESOURCE and PROGRAM names. Both are version details, which is why they are discovered
 * rather than assumed - the discovery just has to look for the right shape. It did not: the
 * pattern was `^MAIN\s+(\w+);`, which cannot match a `_data__` type, and every case failed
 * on it when tier 2 first executed.
 */
export function parseInstance(resourceText: string, programName: string): { structType: string; instance: string } | null {
  const type = programName.toUpperCase()
  const m = new RegExp(`^\\s*(${type}_data__)\\s+(\\w+)\\s*;`, 'm').exec(resourceText)
  return m ? { structType: m[1]!, instance: m[2]! } : null
}

/**
 * Every program instance in the resource file, for a case that declares its own CONFIGURATION.
 *
 * The same `<TYPE>_data__ <RESOURCE>__<INSTANCE>;` shape {@link parseInstance} looks for, collected
 * for every PROGRAM line rather than for one known type; the instance name is the part after the
 * resource's `__`. A task's own state (`static R_TRIG_data__ ...` for an event task) is `static`, so
 * it is not mistaken for one.
 */
export function parseInstances(resourceText: string): { name: string; structType: string; instance: string }[] {
  return [...resourceText.matchAll(/^\s*(\w+_data__)\s+(\w+?)__(\w+)\s*;/gm)].map((m) => ({ name: m[3]!, structType: m[1]!, instance: `${m[2]}__${m[3]}` }))
}

/**
 * The `.c` files that are their own translation unit.
 *
 * MATIEC's `Res0.c` does `#include "POUS.c"` - the POU bodies are text it pulls in, not a
 * separate unit - so handing every `.c` in the directory to the compiler makes `POUS.c`
 * compile alone, without the types its own header supplies, and it fails on its first line.
 * Rather than hard-code the name, drop whatever another `.c` includes.
 */
export function translationUnits(files: { name: string; text: string }[]): string[] {
  const included = new Set<string>()
  for (const f of files) {
    for (const m of f.text.matchAll(/^\s*#\s*include\s+"([^"]+\.c)"/gm)) included.add(m[1]!)
  }
  return files.map((f) => f.name).filter((n) => !included.has(n))
}

/**
 * The IEC type of every variable in the generated PROGRAM struct, read out of POUS.h.
 *
 * The C representation is not guessable from the golden's JavaScript type: a `TIME` is an
 * `IEC_TIMESPEC` STRUCT, so `(double)inst->ET.value` is not merely imprecise, it does not
 * compile. MATIEC writes the type into the struct as `__DECLARE_VAR(TIME,ET)`, so read it
 * from there - the same discover-don't-assume rule {@link parseInstance} follows.
 */
export function declaredTypes(pousHeaderText: string, structType: string): Map<string, string> {
  const types = new Map<string, string>()
  // a located variable is declared through its own macro, with the same (type, NAME) arguments
  for (const m of structBody(pousHeaderText, structType).matchAll(/__DECLARE_(?:VAR|LOCATED)\(\s*(\w+)\s*,\s*(\w+)\s*\)/g)) {
    types.set(m[2]!.toUpperCase(), m[1]!.toUpperCase())
  }
  return types
}

/** The body of the struct for this POU only. The inner pattern is tempered so it cannot run back
 *  through an earlier `typedef struct` - POUS.h declares every function block above the program, and
 *  a plain lazy match starts at the first one and swallows all its fields. */
function structBody(pousHeaderText: string, structType: string): string {
  return new RegExp(`typedef struct \\{((?:(?!typedef struct)[\\s\\S])*?)\\}\\s*${structType};`).exec(pousHeaderText)?.[1] ?? ''
}

/**
 * The LOCATED variables of a POU struct, upper-cased.
 *
 * MATIEC declares a located variable as `__DECLARE_LOCATED(type, NAME)`, a `{ value, flags, fvalue }`
 * record whose `value` is a pointer into storage the runtime provides (one per address, listed in
 * LOCATED_VARIABLES.h), so the harness reaches its payload through that pointer. As
 * measured, a replay that wrote `inst->EYE.value = 1` would have stored into the pointer itself.
 */
export function locatedNames(pousHeaderText: string, structType: string): Set<string> {
  const out = new Set<string>()
  for (const m of structBody(pousHeaderText, structType).matchAll(/__DECLARE_LOCATED\(\s*(\w+)\s*,\s*(\w+)\s*\)/g)) out.add(m[2]!.toUpperCase())
  return out
}

/**
 * One ST variable, as a C lvalue on the instance.
 *
 * Every variable in a generated POU struct is declared through `__DECLARE_VAR(type, NAME)`,
 * which expands to `__IEC_<type>_t NAME;` - a `{ value, flags }` record, not the bare value
 * (matiec lib/C/accessor.h and iec_types_all.h). So the payload is always one `.value` down.
 * This is what matiec's own `__GET_VAR`/`__SET_VAR` macros do; spelling it out keeps the
 * generated harness readable when a case has to be debugged by hand.
 */
function ivar(name: string): string {
  return `inst->${name.toUpperCase()}.value`
}

/** C `printf` conversion for reading one ST variable back out of the image, chosen by the
 *  variable's declared IEC type rather than by the shape of the golden.
 *
 *  - `STRING` is a {len, body[]} record, not a NUL-terminated char*, so the length has to be
 *    passed to emit_string() explicitly.
 *  - `TIME` is an IEC_TIMESPEC {tv_sec, tv_nsec}; the corpus states durations in
 *    milliseconds (`close: { et: 100 }`), which is what every target's TIME carries too, so
 *    it is flattened to ms here rather than compared as a struct. */
function readback(field: string, v: string, kind: string, iecType: string | undefined): string {
  // DATE, TOD and DT are the same IEC_TIMESPEC (seconds since 1970, or since midnight), and the corpus
  // states them in milliseconds from the same origins, so they flatten exactly as TIME does
  if (iecType === 'TIME' || iecType === 'DATE' || iecType === 'TOD' || iecType === 'DT') {
    return `  printf("%s\\"${field}\\":%.17g", sep, (double)(${v}.tv_sec) * 1000.0 + (double)(${v}.tv_nsec) / 1e6); sep = ",";`
  }
  if (kind === 'string' || iecType === 'STRING') return `  printf("%s\\"${field}\\":", sep); emit_string(${v}.body, ${v}.len); sep = ",";`
  if (kind === 'real' || iecType === 'REAL' || iecType === 'LREAL') return `  printf("%s\\"${field}\\":%.17g", sep, (double)(${v})); sep = ",";`
  return `  printf("%s\\"${field}\\":%lld", sep, (long long)(${v})); sep = ",";`
}

/**
 * Generate the driver. It steps the configuration by hand instead of using a runtime loop:
 * set the inputs, advance __CURRENT_TIME by the step's dt, run one scan, print the image.
 * One JSON object per line, so the differ never has to parse C output structurally.
 */
export function renderHarness(
  c: HarnessCase,
  { instance, structType, watched, types = new Map<string, string>(), instances = [], located = new Set<string>() }: HarnessFacts,
): string {
  /** An ST variable as a C lvalue, with its declared type: on the one program, or on the instance
   *  an `Instance.Name` names. A located variable's payload is behind its pointer. */
  const place = (name: string): { lvalue: string; iecType: string | undefined } => {
    const dot = name.indexOf('.')
    const inst = dot < 0 ? undefined : instances.find((i) => i.name.toUpperCase() === name.slice(0, dot).toUpperCase())
    if (inst) {
      const field = name.slice(dot + 1).toUpperCase()
      const lvalue = `${inst.symbol}.${field}.value`
      return { lvalue: inst.located?.has(field) ? `(*${lvalue})` : lvalue, iecType: inst.types.get(field) }
    }
    return { lvalue: located.has(name.toUpperCase()) ? `(*${ivar(name)})` : ivar(name), iecType: types.get(name.toUpperCase()) }
  }
  const steps = c.steps.map((step) => ({
    // STRING inputs are not renderable: MATIEC assigns them through its own
    // __STRING_LITERAL machinery rather than a plain `=`, so a case that needs one carries
    // an `oracle.skip` instead of being written half-correctly here.
    in: Object.entries(step.in ?? {}).map(([k, v]) => [k.toUpperCase(), typeof v === 'boolean' ? (v ? 1 : 0) : v] as const),
    dt: step.dt ?? 0.1,
  }))
  const body = steps
    .map(({ in: ins, dt }) => {
      const writes = ins.map(([k, v]) => `  ${place(k).lvalue} = ${String(v)};`).join('\n')
      return [writes, `  advance(${dt});`, `  config_run__(tick++);`, `  emit();`].filter(Boolean).join('\n')
    })
    .join('\n')

  return `/* generated harness for: ${c.name} */
/* libc before matiec, always - see the note on SHIM_DECLARATIONS for what happens when
   glibc's <math.h> is reached after matiec has defined its __acos/__sqrt/... macros */
#include <stdio.h>
#include <stdarg.h>
#include <math.h>
#include "iec_std_lib.h"
/* the POU state structs (MAIN_data__ and friends) live here, and reaching them needs
   accessor.h first - the same include order MATIEC's own Res0.c uses */
#include "accessor.h"
#include "POUS.h"

/* ---- symbols MATIEC's generated code needs but its lib does not define ----
 *
 * TWO FAMILIES, for two different reasons:
 *
 *  1. iec_lib_* - declared in iec_std_lib.h as "replacement for libc functions in case libc
 *     isn't directly available", and left for the EMBEDDER to supply (Beremiz provides them
 *     from its runtime). A standalone replay has libc, so these just forward to it. Without
 *     them every case touching REAL math, REAL_TO_INT rounding or INT_TO_STRING fails to
 *     LINK - and -lm cannot help, because the missing symbol is iec_lib_fmod, not fmod.
 *  2. _____time_* - emitted for the ST operators +, - and * on TIME, but shipped in no
 *     matiec header (the library defines __time_add/__time_sub/__time_mul, with two
 *     underscores, and ___ADD_TIME for the function form). That looks like a gap in the
 *     compiler rather than a contract for us to fill, so these forward to matiec's own
 *     helpers instead of reimplementing the arithmetic: the semantics under test stay
 *     MATIEC's, which is the whole point of an oracle.
 */
double iec_lib_acos(double x) { return acos(x); }
double iec_lib_asin(double x) { return asin(x); }
double iec_lib_atan(double x) { return atan(x); }
double iec_lib_cos(double x) { return cos(x); }
double iec_lib_exp(double x) { return exp(x); }
double iec_lib_fmod(double x, double y) { return fmod(x, y); }
double iec_lib_log(double x) { return log(x); }
double iec_lib_log10(double x) { return log10(x); }
double iec_lib_pow(double x, double y) { return pow(x, y); }
double iec_lib_sin(double x) { return sin(x); }
double iec_lib_sqrt(double x) { return sqrt(x); }
double iec_lib_tan(double x) { return tan(x); }
int iec_lib_snprintf(char *s, size_t n, const char *fmt, ...) {
  va_list ap; int r;
  va_start(ap, fmt);
  r = vsnprintf(s, n, fmt, ap);
  va_end(ap);
  return r;
}
TIME _____time_add(TIME a, TIME b) { return __time_add(a, b); }
TIME _____time_sub(TIME a, TIME b) { return __time_sub(a, b); }
TIME _____time_mul(TIME a, LREAL b) { return __time_mul(a, b); }

/* ---- the storage behind located variables ----
 *
 * MATIEC points each located variable at storage the RUNTIME provides, named after its address
 * (__IX0_0 for %IX0.0), and lists every one in LOCATED_VARIABLES.h (empty when nothing is located).
 * The generated init does \`extern type *location; name.value = location;\`, so the harness defines the
 * values and then the pointers, in two passes over that list: how Beremiz's and OpenPLC's glue do it. */
#define __LOCATED_VAR(type, name, ...) type __##name;
#include "LOCATED_VARIABLES.h"
#undef __LOCATED_VAR
#define __LOCATED_VAR(type, name, ...) type *name = &__##name;
#include "LOCATED_VARIABLES.h"
#undef __LOCATED_VAR

TIME __CURRENT_TIME;
BOOL __DEBUG;
extern unsigned long long common_ticktime__;
void config_init__(void);
void config_run__(unsigned long tick);
/* the instance MATIEC generated in the resource file, and its state struct */
extern ${structType} ${instance};
${instances.filter((i) => i.symbol !== instance).map((i) => `extern ${i.structType} ${i.symbol};`).join('\n')}
static ${structType} *inst = &${instance};
/* FROM 1, deliberately. MATIEC runs a task when tick % (INTERVAL / common tick) == 0, which releases
   every task at tick 0; this engine's scheduler brings a task's first scan due one full period in
   (src/plc/scanEngine.ts). IEC says neither, so the ticks are numbered to line the two phases up: a
   task on every third tick runs on the 3rd, 6th, ... call here and on the 3rd, 6th, ... step there.
   With one task (every corpus case before tasks existed) every tick runs it either way. */
static unsigned long tick = 1;

/* MATIEC's timers read __CURRENT_TIME, so a deterministic replay drives it by hand
   instead of sampling the wall clock. */
static void advance(double dt) {
  long long ns = __CURRENT_TIME.tv_nsec + (long long)(dt * 1e9 + 0.5);
  __CURRENT_TIME.tv_sec += ns / 1000000000LL;
  __CURRENT_TIME.tv_nsec = ns % 1000000000LL;
}

/* A MATIEC STRING is {len, body[]} rather than a C string, so this writes exactly len
   bytes as a JSON string, escaping what JSON requires. */
static void emit_string(const unsigned char *body, unsigned int len) {
  unsigned int i;
  putchar('"');
  for (i = 0; i < len; i++) {
    unsigned char ch = body[i];
    if (ch == '"' || ch == '\\\\') printf("\\\\%c", ch);
    else if (ch < 0x20) printf("\\\\u%04x", ch);
    else putchar(ch);
  }
  putchar('"');
}

static void emit(void) {
  const char *sep = "";
  printf("{");
${watched
  .map(({ name, kind }) => {
    const { lvalue, iecType } = place(name)
    return readback(name.toUpperCase(), lvalue, kind, iecType)
  })
  .join('\n')}
  printf("}\\n");
}

int main(void) {
  __CURRENT_TIME.tv_sec = 0;
  __CURRENT_TIME.tv_nsec = 0;
  config_init__();
${body}
  return 0;
}
`
}
