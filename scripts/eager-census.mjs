// Eager-JS census: what is actually IN the graph the /app/ shell must parse before the first
// frame, attributed to the source modules that own it.
//
// Why: when the eager-JS checks (scripts/lib/eager-js.mjs) fail they can only name a chunk, and most
// of the graph is two chunks, so that says nothing about what to do. This is draw-census.mjs for
// bytes. It also shows modules that reached the eager graph by STATIC REACHABILITY ACCIDENT rather
// than need (a barrel re-export once pulled four lazy-only PLCopen modules into the first frame).
//
// Method: build with sourcemaps into a scratch dir (never dist/), then attribute each generated
// byte of every eager chunk to its source module. Bytes are RAW, the axis parse/compile cost rides
// on; brotli is per chunk only, since compression is not additive per module.
//
// Usage:
//   npm run eager-census                   # build with sourcemaps, then report
//   npm run eager-census -- --no-build     # re-report the last census build
//   npm run eager-census -- --top 40       # more individual modules (default 25)
//   npm run eager-census -- --depth 3      # finer buckets (default: src/<layer>, node_modules/<pkg>)
// Each run records its per-module sizes (.eager-js/last-census.json) and lists what moved since the
// last run, so a census before a change and one after it name what the change added to the first frame.
/* global console, process, URL */
import { existsSync, readFileSync, rmSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { eagerJsChunks, EAGER_JS_BUDGET_BR_MB, EAGER_JS_BUDGET_RAW_MB, readEagerRecord, writeEagerRecord } from './lib/eager-js.mjs'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const OUT = resolve(ROOT, '.eager-census')
const arg = (flag, dflt) => {
  const i = process.argv.indexOf(flag)
  return i === -1 ? dflt : Number(process.argv[i + 1])
}
const TOP = arg('--top', 25)
const DEPTH = arg('--depth', 2)
const NO_BUILD = process.argv.includes('--no-build')

// ---- sourcemap attribution -------------------------------------------------------------------
const B64 = new Map([...'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'].map((c, i) => [c, i]))

/** Decode one VLQ-encoded mapping segment into its integer fields. */
function decodeSegment(str) {
  const out = []
  let value = 0
  let shift = 0
  for (const ch of str) {
    const digit = B64.get(ch)
    if (digit === undefined) return out // malformed: stop rather than invent numbers
    value += (digit & 31) << shift
    if (digit & 32) { shift += 5; continue }
    const negative = value & 1
    value >>= 1
    out.push(negative ? (value === 0 ? -0x80000000 : -value) : value)
    value = 0
    shift = 0
  }
  return out
}

/**
 * Generated bytes per source index for one chunk, plus what no mapping claims.
 * A segment owns from its generated column up to the next segment's (or the line's end); a
 * segment with no source field (length < 4) and the head of a line before its first segment are
 * unmapped. Line terminators are counted unmapped rather than guessed at.
 */
function attribute(code, map) {
  const bytes = new Map()
  let unmapped = 0
  const lines = code.split('\n')
  const groups = map.mappings.split(';')
  let srcIdx = 0
  for (let ln = 0; ln < groups.length; ln++) {
    const lineLen = lines[ln] === undefined ? 0 : lines[ln].length
    if (ln < lines.length) unmapped += 1 // the '\n' (or, on the last line, nothing to over-count)
    if (!groups[ln]) { unmapped += lineLen; continue }
    const segs = groups[ln].split(',').map(decodeSegment)
    let genCol = 0
    const starts = []
    for (const s of segs) {
      if (!s.length) continue
      genCol += s[0]
      if (s.length >= 4) { srcIdx += s[1]; starts.push([genCol, srcIdx]) }
      else starts.push([genCol, -1])
    }
    if (!starts.length) { unmapped += lineLen; continue }
    if (starts[0][0] > 0) unmapped += starts[0][0]
    for (let i = 0; i < starts.length; i++) {
      const from = starts[i][0]
      const to = i + 1 < starts.length ? starts[i + 1][0] : lineLen
      const n = Math.max(0, to - from)
      if (starts[i][1] === -1) unmapped += n
      else bytes.set(starts[i][1], (bytes.get(starts[i][1]) ?? 0) + n)
    }
  }
  return { bytes, unmapped }
}

/** A sourcemap `sources` entry as a repo-relative path (or a label for the virtual ones). */
function normalizeSource(src, mapDir) {
  if (!src) return '(anonymous)'
  if (src.startsWith('\0') || src.includes('\0')) return `(virtual) ${src.replace(/\0/g, '')}`
  if (/^(virtual:|vite\/|plugin-vue|rolldown:)/.test(src)) return `(virtual) ${src}`
  const abs = resolve(mapDir, src)
  const rel = relative(ROOT, abs).replace(/\\/g, '/')
  return rel.startsWith('..') ? src.replace(/\\/g, '/') : rel
}

/** The bucket a module is charged to: node_modules/<pkg>, src/<layer>[/<dir>], or its own head. */
function bucketOf(path) {
  if (path.startsWith('(')) return '(unattributable)'
  const nm = path.lastIndexOf('node_modules/')
  if (nm !== -1) {
    const rest = path.slice(nm + 'node_modules/'.length).split('/')
    return `node_modules/${rest[0].startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0]}`
  }
  const parts = path.split('/')
  return parts.slice(0, Math.max(1, DEPTH)).join('/')
}

// ---- build -----------------------------------------------------------------------------------
async function buildWithSourcemaps() {
  console.log('building with sourcemaps into .eager-census/ (this does not touch dist/) ...')
  const { build } = await import('vite')
  rmSync(OUT, { recursive: true, force: true })
  await build({
    configFile: resolve(ROOT, 'vite.config.ts'),
    logLevel: 'warn',
    // no public/ copy: this build exists to be measured, and copying ~80 MB of models and textures
    // into it costs more time than the whole census. It does not change chunking, which is what is
    // being measured. (With the copy the scratch dir is 154 MB.)
    publicDir: false,
    build: { outDir: OUT, emptyOutDir: true, sourcemap: true },
  })
}

// ---- report ----------------------------------------------------------------------------------
const kb = (n) => `${(n / 1024).toFixed(1)} KB`
const pad = (s, n) => String(s).padEnd(n)
const padL = (s, n) => String(s).padStart(n)

async function main() {
  if (!NO_BUILD) await buildWithSourcemaps()
  const chunks = eagerJsChunks(OUT)
  if (!chunks.length) {
    console.error(`no built app shell in ${OUT} - run without --no-build`)
    process.exit(1)
  }

  const perModule = new Map()
  let unmappedTotal = 0
  let noMap = 0
  for (const c of chunks) {
    const mapFile = `${c.file}.map`
    if (!existsSync(mapFile)) { noMap += c.raw; continue }
    const map = JSON.parse(readFileSync(mapFile, 'utf8'))
    if (map.sections) { noMap += c.raw; continue } // index maps: not worth decoding for this
    const mapDir = dirname(mapFile)
    const names = map.sources.map((s) => normalizeSource(s, mapDir))
    const { bytes, unmapped } = attribute(readFileSync(c.file, 'utf8'), map)
    unmappedTotal += unmapped
    for (const [i, n] of bytes) {
      const key = names[i] ?? '(anonymous)'
      perModule.set(key, (perModule.get(key) ?? 0) + n)
    }
  }

  const rawTotal = chunks.reduce((s, c) => s + c.raw, 0)
  const brTotal = chunks.reduce((s, c) => s + c.br, 0)

  console.log('\nEager chunks (what /app/index.html pulls before anything else):')
  for (const c of chunks) {
    console.log(`  ${padL(kb(c.raw), 10)} raw  ${padL(kb(c.br), 9)} br   ${c.url}`)
  }
  console.log(`  ${padL(kb(rawTotal), 10)} raw  ${padL(kb(brTotal), 9)} br   TOTAL`)
  console.log(
    `\n  raw    ${(rawTotal / 1e6).toFixed(3)} MB (ceiling ${EAGER_JS_BUDGET_RAW_MB.toFixed(2)} MB)` +
      `\n  brotli ${(brTotal / 1e6).toFixed(3)} MB (ceiling ${EAGER_JS_BUDGET_BR_MB.toFixed(2)} MB)`,
  )

  const buckets = new Map()
  for (const [path, n] of perModule) {
    const b = bucketOf(path)
    buckets.set(b, (buckets.get(b) ?? 0) + n)
  }
  if (unmappedTotal) buckets.set('(unmapped: runtime, banners, glue)', unmappedTotal)
  if (noMap) buckets.set('(no sourcemap emitted)', noMap)

  console.log('\nWhere the raw bytes come from:')
  for (const [b, n] of [...buckets].sort((a, x) => x[1] - a[1])) {
    console.log(`  ${padL(kb(n), 10)}  ${padL(`${((n / rawTotal) * 100).toFixed(1)}%`, 6)}  ${b}`)
  }

  console.log(`\nTop ${TOP} modules:`)
  for (const [path, n] of [...perModule].sort((a, x) => x[1] - a[1]).slice(0, TOP)) {
    console.log(`  ${padL(kb(n), 10)}  ${pad(path, 0)}`)
  }

  const last = readEagerRecord(ROOT, 'last-census.json')
  writeEagerRecord(ROOT, 'last-census.json', { raw: rawTotal, modules: Object.fromEntries(perModule) })
  if (last) {
    const before = last.modules ?? {}
    const signed = (n) => `${n >= 0 ? '+' : '-'}${kb(Math.abs(n))}`
    const moved = [...new Set([...perModule.keys(), ...Object.keys(before)])]
      .map((n) => ({ n, d: (perModule.get(n) ?? 0) - (before[n] ?? 0), isNew: !(n in before) }))
      .filter((r) => Math.abs(r.d) >= 256)
      .sort((a, b) => b.d - a.d)
    console.log(`\nSince the last census (${signed(rawTotal - last.raw)} raw in all):`)
    if (!moved.length) console.log('  no module moved by more than 0.25 KB')
    for (const r of moved.slice(0, TOP)) console.log(`  ${padL(signed(r.d), 11)}  ${r.n}${r.isNew ? '  (new in the first frame)' : ''}`)
  }

  console.log(
    '\nA module here is a module the first frame WAITS for. If one of these is only reached from a' +
      '\npanel, a dialog or a file door, it belongs behind a dynamic import - and check the barrels:' +
      '\na re-export edge puts a module in the eager chunk whether or not the eager side uses it.',
  )
}

main()
