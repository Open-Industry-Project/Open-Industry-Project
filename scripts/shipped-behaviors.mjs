// The SHA-256 of every first-party part behavior this app has ever shipped: src/editor/shippedBehaviorHashes.ts.
//
// A collab room keeps a snapshot of every built-in part it places, code included. Once a deploy changes a
// built-in's behavior, every older room holds code that no longer matches what this build ships. Without this list
// the room's code-trust gate (src/collab/codeTrust.ts) treats that as a stranger's code and asks the user about it.
// The list lets it recognise the app's own earlier code. Append-only: a version once shipped stays
// trusted, because rooms holding it never go away.
//
//   node scripts/shipped-behaviors.mjs            add every version in git history + the working tree
//   node scripts/shipped-behaviors.mjs --check    fail if a current behavior's hash is missing (CI / pre-commit)
//
// The hashed text is what the app hashes at run time: the file with CRLF turned into LF
// (src/editor/bundledPackageData.ts `lf`), which buildPackage keeps verbatim.
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(root, 'src/editor/shippedBehaviorHashes.ts')
const OUT_NAME = 'src/editor/shippedBehaviorHashes.ts'
const PARTS = 'examples/parts'

const lf = (s) => s.replace(/\r\n/g, '\n')
const hash = (s) => createHash('sha256').update(lf(s), 'utf8').digest('hex')
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })

function workingTreeHashes() {
  const out = new Map()
  for (const dir of readdirSync(join(root, PARTS))) {
    const file = join(root, PARTS, dir, 'behavior.ts')
    if (existsSync(join(root, PARTS, dir, 'rig.json')) && existsSync(file)) out.set(hash(readFileSync(file, 'utf8')), `${dir} (working tree)`)
  }
  return out
}

function historyHashes() {
  const out = new Map()
  const commits = git('log', '--format=%H', '--', `${PARTS}/*/behavior.ts`).split('\n').filter(Boolean)
  for (const c of commits) {
    const files = git('ls-tree', '-r', '--name-only', c, '--', PARTS).split('\n').filter((f) => /\/behavior\.ts$/.test(f))
    for (const f of files) out.set(hash(git('show', `${c}:${f}`)), `${f} @ ${c.slice(0, 7)}`)
  }
  return out
}

const existing = new Set(existsSync(OUT) ? (readFileSync(OUT, 'utf8').match(/[0-9a-f]{64}/g) ?? []) : [])
const current = workingTreeHashes()

if (process.argv.includes('--check')) {
  const missing = [...current].filter(([h]) => !existing.has(h))
  if (missing.length) {
    console.error(`FAIL  ${missing.length} first-party behavior(s) not in ${OUT_NAME}:`)
    for (const [h, where] of missing) console.error(`      ${where}  ${h.slice(0, 12)}`)
    console.error('      run: node scripts/shipped-behaviors.mjs')
    process.exit(1)
  }
  console.log(`PASS  all ${current.size} first-party behaviors are in the shipped list (${existing.size} versions)`)
} else {
  const all = new Set([...existing, ...historyHashes().keys(), ...current.keys()])
  const body = [...all]
    .sort()
    .map((h) => `  '${h}',`)
    .join('\n')
  writeFileSync(
    OUT,
    '// GENERATED by scripts/shipped-behaviors.mjs - do not edit. The SHA-256 of every first-party behavior.ts ever\n' +
      '// shipped (see src/editor/shippedBehaviors.ts). Append-only: re-run the script after changing a part.\n' +
      `export const SHIPPED_BEHAVIOR_HASHES: readonly string[] = [\n${body}\n]\n`,
  )
  console.log(`wrote ${all.size} hashes (${all.size - existing.size} new) to ${OUT_NAME}`)
}
